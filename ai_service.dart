import 'dart:convert';
import 'package:http/http.dart' as http;

/// خدمة الذكاء الاصطناعي
/// تدعم الاتصال بـ OpenAI أو أي API متوافق
class AiService {
  // إعدادات API - غيّرها حسب مزود الخدمة
  static const String _apiKey = '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';
  static const String _baseUrl = 'https://api.groq.com/openai/v1/chat/completions';
  static const String _model = 'llama-3.1-70b-versatile';

  /// إرسال رسالة والحصول على رد
  Future<String> sendMessage({
    required String message,
    required List<Map<String, String>> history,
  }) async {
    // إذا لم يتم تعيين مفتاح API، استخدم الردود المحلية
    if (_apiKey == 'YOUR_API_KEY_HERE') {
      return _getLocalResponse(message);
    }

    try {
      final messages = [
        {
          'role': 'system',
          'content': '''أنت مساعد قانوني ذكي متخصص في قوانين المملكة العربية السعودية ودول الخليج ومصر والأردن.

قواعد مهمة:
- قدم معلومات قانونية دقيقة ومحدثة
- اذكر أن المعلومات للإرشاد فقط ولا تغني عن استشارة محامي
- استخدم لغة عربية واضحة ومفهومة
- إذا لم تكن متأكداً، قل ذلك بوضوح
- اقترح الخطوات العملية عند الإمكان'''
        },
        ...history,
        {'role': 'user', 'content': message},
      ];

      final response = await http.post(
        Uri.parse(_baseUrl),
        headers: {
          'Content-Type': 'application/json',
          'Authorization': 'Bearer $_apiKey',
        },
        body: jsonEncode({
          'model': _model,
          'messages': messages,
          'temperature': 0.7,
          'max_tokens': 1000,
        }),
      );

      if (response.statusCode == 200) {
        final data = jsonDecode(utf8.decode(response.bodyBytes));
        return data['choices'][0]['message']['content'] as String;
      } else {
        return 'عذراً، حدث خطأ في الاتصال. حاول مرة أخرى.\n(${response.statusCode})';
      }
    } catch (e) {
      return 'عذراً، تعذر الاتصال بالخادم. تأكد من اتصالك بالإنترنت.';
    }
  }

  /// ردود محلية للاختبار (بدون API)
  String _getLocalResponse(String message) {
    final q = message.toLowerCase();

    if (q.contains('مستأجر') || q.contains('إيجار')) {
      return '''وفقاً لنظام الإيجار في المملكة العربية السعودية:

**حقوق المستأجر:**
• الحق في السكن الهادئ دون إزعاج
• عدم دخول المالك للعقار دون إذن مسبق
• صيانة العقار من قبل المالك
• تجديد العقد وفق الشروط المتفق عليها

**واجبات المستأجر:**
• دفع الإيجار في موعده
• الحفاظ على العقار
• عدم إجراء تعديلات دون موافقة

⚠️ هذه المعلومات للإرشاد فقط. للحالات الخاصة، يُنصح باستشارة محامي متخصص.''';
    }

    if (q.contains('توكيل')) {
      return '''**كيفية إعداد توكيل رسمي:**

1. **تحديد نوع التوكيل:**
   - توكيل عام: يشمل جميع التصرفات
   - توكيل خاص: لموضوع محدد

2. **الخطوات:**
   - التوجه لكاتب العدل أو استخدام منصة ناجز
   - إحضار الهوية الأصلية
   - تحديد الصلاحيات بدقة
   - دفع الرسوم

3. **ملاحظات مهمة:**
   - يمكن إلغاء التوكيل في أي وقت
   - يُفضل تحديد مدة للتوكيل

هل تريد توليد نموذج توكيل؟''';
    }

    if (q.contains('إجازة') || q.contains('عمل') || q.contains('عامل')) {
      return '''**حقوق العامل حسب نظام العمل السعودي:**

**الإجازات:**
• السنوية: 21 يوماً (30 بعد 5 سنوات خدمة)
• المرضية: 30 يوماً بأجر كامل
• الزواج: 5 أيام
• الوفاة: 5 أيام
• الحج: 10-15 يوماً (مرة واحدة)

**حقوق أخرى:**
• مكافأة نهاية الخدمة
• ساعات عمل لا تتجاوز 8 يومياً
• راحة أسبوعية

⚠️ للمزيد من التفاصيل، راجع نظام العمل أو استشر محامي متخصص.''';
    }

    if (q.contains('طلاق') || q.contains('زواج') || q.contains('حضانة')) {
      return '''**الأحوال الشخصية:**

**الزواج:**
• يتطلب موافقة الطرفين
• عقد شرعي موثق
• يمكن إجراءه عبر منصة ناجز

**الطلاق:**
• يُوثق في المحكمة
• للزوجة حقوق مالية محددة
• الحضانة للأم غالباً حتى سن معينة

**الحضانة:**
• الأم لها الأولوية في الحضانة
• الأب يتحمل النفقة
• حق الزيارة مكفول

⚠️ هذه قضايا حساسة تحتاج استشارة محامي متخصص.''';
    }

    return '''شكراً لسؤالك.

بناءً على المعلومات المتاحة، هذا الموضوع يحتاج إلى مراجعة النصوص القانونية ذات الصلة في النظام المعمول به في بلدك.

**أنصحك بـ:**
1. البحث في القوانين المتعلقة بالموضوع
2. استشارة محامي متخصص لحالتك الخاصة
3. مراجعة الجهات الرسمية المختصة

هل تريد أن أساعدك في البحث عن موضوع معين؟''';
  }
}
